    let canonical = document.querySelector(

        'link[rel="canonical"]'

    );



    if (!canonical) {

        canonical = document.createElement('link');

        canonical.setAttribute(

            'rel',

            'canonical'

        );

        document.head.appendChild(canonical);

    }



