// Get SEO information for a product

function getProductSEO(product) {

    if (!product) return null;



    return {

        title: product.seo?.title || `${product.name} Price in Bangladesh`,

        description:

            product.seo?.description ||

            `Buy ${product.name} in Bangladesh at an affordable price.`,

        keywords:

            product.seo?.keywords ||

            `${product.name}, ${product.name} price Bangladesh`

    };

}





// =====================================================

// 🏷️ PRODUCT SEO DATA GENERATOR

// =====================================================



function getProductStructuredData(product, siteUrl = window.location.origin) {

    if (!product) return null;



    const seo = getProductSEO(product);



    return {

        "@context": "https://schema.org",

        "@type": "Product",

        "name": product.name,

        "description": product.desc,

        "image": product.images || [product.img],

        "brand": {

            "@type": "Brand",

            "name": product.brand

        },

        "category": product.cat,

        "sku": String(product.id),

        "offers": {

            "@type": "Offer",

            "url": `${siteUrl}/product.html?id=${product.id}`,

            "priceCurrency": "BDT",

            "price": String(product.price),

            "availability": "https://schema.org/InStock",

            "itemCondition":

                product.type === 'used'

                    ? "https://schema.org/UsedCondition"

                    : "https://schema.org/NewCondition"

        }

    };

}





